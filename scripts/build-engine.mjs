#!/usr/bin/env node
// Bundles Prep Room's language engine (lib/run in the site's repo) into server/engine/:
// the starters for every language a question runs in, and the harness that runs a
// person's code against the examples. The plugin runs it on the person's own machine, so
// a run costs Prep Room nothing. It is split because Claude's directory holds any file
// over 256 KiB for a reviewer; test/server.test.mjs fails if one grows past that.
//
//   node scripts/build-engine.mjs /path/to/preproom
//
// Run it again whenever lib/run changes in the site's repo, then commit server/engine/.
// Needs network once, for npx to fetch esbuild.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const site = resolve(process.argv[2] || join(here, '..', '..', 'preproom'))
if (!existsSync(join(site, 'lib/run/drivers.ts'))) {
  console.error(`No Prep Room repo at ${site}. Pass its path: node scripts/build-engine.mjs /path/to/preproom`)
  process.exit(1)
}

const sha = (() => { try { return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: site }).toString().trim() } catch { return 'unknown' } })()
const tmp = mkdtempSync(join(tmpdir(), 'preproom-engine-'))
writeFileSync(join(tmp, 'drivers.ts'), `export { buildDriver, parseRunStdout, approxEqual, renderValue, readCompileError, DRIVER_LANGS } from '${site}/lib/run/drivers'\n`)
writeFileSync(join(tmp, 'langs.ts'), `export { starterFor, genStarter, signatureLine, fnNameIn, LANG_NAME, LANG_FILE, LANG_ORDER, isLanguage } from '${site}/lib/run/langs'\n`)

const out = join(here, '..', 'server', 'engine')
rmSync(out, { recursive: true, force: true })
execFileSync('npx', ['-y', 'esbuild@0.25.10', join(tmp, 'drivers.ts'), join(tmp, 'langs.ts'), '--bundle', '--splitting', '--format=esm', '--platform=node', '--target=node20', '--log-level=warning', '--out-extension:.js=.mjs', '--chunk-names=shared-[hash]', `--outdir=${out}`, `--banner:js=// Generated by scripts/build-engine.mjs from Prep Room's lib/run (site commit ${sha}). Do not edit.`], { cwd: site, stdio: 'inherit' })
rmSync(tmp, { recursive: true, force: true })

for (const f of readdirSync(out)) console.log(`Wrote server/engine/${f} (${Math.round(statSync(join(out, f)).size / 1024)} KB)`)
console.log(`From ${site} at ${sha}`)
