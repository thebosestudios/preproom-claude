#!/usr/bin/env node
// Bundles Prep Room's language engine (lib/run in the site's repo) into
// server/engine.mjs: the starters for every language a question runs in, and the
// harness that runs a person's code against the examples. The plugin runs it on
// the person's own machine, so a run costs Prep Room nothing.
//
//   node scripts/build-engine.mjs /path/to/preproom
//
// Run it again whenever lib/run changes in the site's repo, then commit
// server/engine.mjs. Needs network once, for npx to fetch esbuild.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const site = resolve(process.argv[2] || join(here, '..', '..', 'preproom'))
if (!existsSync(join(site, 'lib/run/drivers.ts'))) {
  console.error(`No Prep Room repo at ${site}. Pass its path: node scripts/build-engine.mjs /path/to/preproom`)
  process.exit(1)
}

const entry = `
export { buildDriver, parseRunStdout, approxEqual, renderValue, readCompileError, DRIVER_LANGS } from './lib/run/drivers'
export { starterFor, genStarter, signatureLine, fnNameIn, LANG_NAME, LANG_FILE, LANG_ORDER, isLanguage } from './lib/run/langs'
`
const out = join(here, '..', 'server', 'engine.mjs')
execFileSync('npx', ['-y', 'esbuild@0.25.10', '--bundle', '--format=esm', '--platform=node', '--target=node20', '--log-level=warning', `--outfile=${out}`, '--sourcefile=engine-entry.ts', '--loader=ts'], {
  cwd: site,
  input: entry,
  stdio: ['pipe', 'inherit', 'inherit'],
})

const sha = (() => { try { return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: site }).toString().trim() } catch { return 'unknown' } })()
const body = readFileSync(out, 'utf8')
writeFileSync(out, `// Generated by scripts/build-engine.mjs from Prep Room's lib/run (site commit ${sha}). Do not edit.\n${body}`)
console.log(`Wrote ${out} (${Math.round(body.length / 1024)} KB) from ${site} at ${sha}`)
